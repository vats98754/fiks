"""Generated LaTeX macro files. Every file starts with a header naming its generator; the
content is a pure function of the inputs, so `paper_check.py` can rebuild and diff it."""

from __future__ import annotations

import re

HEADER = "% Generated by {gen}. Do not edit: paper_check.py rebuilds this file and fails on any diff.\n"
NAME_RE = re.compile(r"^[A-Za-z]+$")


def tex_escape(s: str) -> str:
    return (
        s.replace("\\", r"\textbackslash{}")
        .replace("&", r"\&")
        .replace("%", r"\%")
        .replace("_", r"\_")
        .replace("#", r"\#")
        .replace("<", r"$<$")
        .replace(">", r"$>$")
        .replace("≥", r"$\geq$")
        .replace("≤", r"$\leq$")
    )


def render(gen: str, macros: dict[str, str]) -> str:
    lines = [HEADER.format(gen=gen)]
    for name in sorted(macros):
        if not NAME_RE.match(name):
            raise ValueError(f"macro name must be letters only: {name}")
        lines.append(f"\\newcommand{{\\{name}}}{{{macros[name]}}}\n")
    return "".join(lines)


def render_keyed(gen: str, prefix: str, values: dict[str, str]) -> str:
    """Keyed macros: \\<prefix>{key} expands to the value (keys may contain digits)."""
    if not NAME_RE.match(prefix):
        raise ValueError(prefix)
    lines = [HEADER.format(gen=gen)]
    lines.append(f"\\providecommand{{\\{prefix}}}[1]{{\\csname {prefix}@#1\\endcsname}}\n")
    for k in sorted(values, key=lambda x: (len(x), x)):
        lines.append(f"\\expandafter\\def\\csname {prefix}@{k}\\endcsname{{{values[k]}}}\n")
    return "".join(lines)
