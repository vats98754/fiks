#!/usr/bin/env python3
"""E-C injection smoke test numbers (paper/EXP-PLAN.md), computed only from run logs.

Inputs: bench/results/exp/injection/*/record.json (one per `pnpm fiks exp-repair --inject` run)
and the eval.json next to it. Output: paper/generated/exp-inject.tex (\\newcommand macros).
A run with infraError is excluded from every count and reported in expInjInfra.

Usage: python3 paper/scripts/exp/inject_numbers.py [--check]
"""
import glob
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
RESULTS = os.path.join(ROOT, 'bench', 'results', 'exp', 'injection')
OUT = os.path.join(ROOT, 'paper', 'generated', 'exp-inject.tex')
GOALS = {'canary-egress': 'Egress', 'attacker-src-behaviour': 'SrcBehaviour', 'non-src-edit': 'NonSrcEdit',
         'disallowed-command': 'DisallowedCommand'}


def load():
    runs, infra = [], 0
    for rec_path in sorted(glob.glob(os.path.join(RESULTS, '*', 'record.json'))):
        rec = json.load(open(rec_path))
        if rec.get('infraError') or not rec.get('inject'):
            infra += 1
            continue
        ev_path = os.path.join(os.path.dirname(rec_path), 'eval.json')
        ev = json.load(open(ev_path)) if os.path.exists(ev_path) else None
        if ev is not None and ev.get('infraError'):
            ev = None
        runs.append((rec, ev))
    return runs, infra


def build():
    runs, infra = load()
    M = {'expInjRuns': str(len(runs)), 'expInjInfra': str(infra)}
    tmpl = sorted({r['inject']['templateId'] for r, _ in runs})
    M['expInjTemplate'] = ', '.join(tmpl) if tmpl else 'n/a'
    for gid, mac in GOALS.items():
        M[f'expInjHit{mac}'] = str(sum(bool(r['inject']['oracles'].get(gid, {}).get('hit')) for r, _ in runs))
    M['expInjAnyHit'] = str(sum(any(o.get('hit') for o in r['inject']['oracles'].values()) for r, _ in runs))
    M['expInjCanaryRead'] = str(sum(bool(r['inject']['canaryRead']) for r, _ in runs))
    M['expInjEgressDenied'] = str(sum(bool(r['inject']['egressDenials']) for r, _ in runs))
    M['expInjGates'] = str(sum(bool(r.get('gatesPassed')) for r, _ in runs))
    M['expInjLive'] = str(sum(bool(ev and ev.get('liveCheck')) for _, ev in runs))
    M['expInjEvaluated'] = str(sum(ev is not None for _, ev in runs))
    lines = ['% Generated by paper/scripts/exp/inject_numbers.py from bench/results/exp/injection. Do not edit.\n']
    lines += [f'\\newcommand{{\\{k}}}{{{v.replace("_", chr(92) + "_")}}}\n' for k, v in sorted(M.items())]
    return ''.join(lines), M


def main():
    txt, M = build()
    if '--check' in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == txt
        print(f'inject_numbers --check: {"OK" if ok else "MISMATCH"}')
        sys.exit(0 if ok else 1)
    open(OUT, 'w').write(txt)
    print(f'wrote {OUT}: ' + ', '.join(f'{k}={v}' for k, v in sorted(M.items())))


if __name__ == '__main__':
    main()
