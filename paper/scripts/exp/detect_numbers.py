#!/usr/bin/env python3
"""E-B detection-sweep numbers (paper/EXP-PLAN.md), computed only from run logs. Stdlib only.

Inputs (written by `pnpm fiks exp-detect clean|mutate`, never by hand):
  bench/results/exp/detect/<runId>/clean.jsonl    one row per clean v1 call (verdict, propertyIds, entities)
  bench/results/exp/detect/<runId>/mutate.jsonl   one row per (operator, call, seed), plus control rows

Outputs:
  paper/generated/exp-detect.tex   \\newcommand macros
  paper/generated/tab-detect.tex   operator | applicable calls | flagged | tool error | recall | coupled?

The run used is the newest <runId> holding clean.jsonl (or --run). Its mutate.jsonl, when present,
gives the mutation numbers. With no run at all every macro is "--" and the table says so.

Usage:
  python3 paper/scripts/exp/detect_numbers.py [--dir DIR] [--run ID] [--out DIR]   # write outputs
  python3 paper/scripts/exp/detect_numbers.py --check [...]                       # exit 1 if outputs differ
"""
import argparse
import json
import math
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
DEFAULT_DIR = os.path.join(ROOT, 'bench', 'results', 'exp', 'detect')
DEFAULT_OUT = os.path.join(ROOT, 'paper', 'generated')
GEN = 'paper/scripts/exp/detect_numbers.py'
HEADER = f'% Generated by {GEN} from bench/results/exp/detect. Do not edit.\n'

RESPONSE_OPS = [f'M{i}' for i in range(1, 15)]
BENIGN_OPS = [f'B{i}' for i in range(1, 5)]
WORDS = ['Zero', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten',
         'Eleven', 'Twelve', 'Thirteen', 'Fourteen']
NA = '--'


def wilson(c, n, z=1.959964):
    """95% Wilson score interval (same formula as paper/scripts/pilot_numbers.py)."""
    if n == 0:
        return (0.0, 1.0)
    p = c / n
    den = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / den
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return (max(0.0, centre - half), min(1.0, centre + half))


def pct(c, n, d=1):
    return NA if n == 0 else f'{100 * c / n:.{d}f}\\%'


def pct_of(x, d=1):
    return f'{100 * x:.{d}f}\\%'


def op_name(op):
    """M12 -> MTwelve (macro names are letters only)."""
    return op[0] + WORDS[int(op[1:])]


def read_jsonl(path):
    with open(path, encoding='utf-8') as f:
        return [json.loads(line) for line in f if line.strip()]


def pick_run(base, run):
    if run:
        return run if os.path.isfile(os.path.join(base, run, 'clean.jsonl')) else None
    if not os.path.isdir(base):
        return None
    runs = sorted(d for d in os.listdir(base) if os.path.isfile(os.path.join(base, d, 'clean.jsonl')))
    return runs[-1] if runs else None


def clean_numbers(rows):
    n = len(rows)
    violated = [r for r in rows if r['verdict'] == 'violated']
    entities = sorted({e for r in rows for e in r.get('entities', [])})
    bad_entities = sorted({e for r in violated for e in r.get('entities', [])})
    return {
        'expDetectCleanCalls': str(n),
        'expDetectCleanViolated': str(len(violated)),
        'expDetectCleanVerified': str(sum(1 for r in rows if r['verdict'] == 'verified')),
        'expDetectCleanUnverifiable': str(sum(1 for r in rows if r['verdict'] == 'unverifiable')),
        'expDetectCleanEntities': str(len(entities)),
        'expDetectCleanEntitiesViolated': str(len(bad_entities)),
        'expDetectWilsonUpperCall': pct_of(wilson(len(violated), n)[1]) if n else NA,
        'expDetectWilsonUpperEntity': pct_of(wilson(len(bad_entities), len(entities))[1]) if entities else NA,
    }


def op_stats(rows, op):
    mine = [r for r in rows if r['op'] == op]
    app = [r for r in mine if r['applicable']]
    flagged = sum(1 for r in app if r.get('flagged'))
    err = sum(1 for r in app if r.get('toolError'))
    coupled = next((r.get('coupled') for r in mine), None)
    in_contracts = next((r.get('coupledInContracts') for r in mine), None)
    return {'rows': len(mine), 'applicable': len(app), 'flagged': flagged, 'toolError': err, 'coupled': coupled,
            'coupledInContracts': in_contracts}


def coupled_cell(s):
    if s['rows'] == 0:
        return NA
    if not s['coupled']:
        return 'no'
    # A coupled kind the contracts do not contain cannot fire: say so instead of implying a check.
    return s['coupled'] if s['coupledInContracts'] is not False else f"{s['coupled']} (no such check)"


def mutate_numbers(rows):
    m = {}
    stats = {op: op_stats(rows, op) for op in RESPONSE_OPS + BENIGN_OPS}
    for op, s in stats.items():
        name = op_name(op)
        m[f'expDetectApplicable{name}'] = str(s['applicable'])
        m[f'expDetectFlagged{name}'] = str(s['flagged'])
        m[f'expDetectToolError{name}'] = str(s['toolError'])
        key = 'expDetectRecall' if op.startswith('M') else 'expDetectFalseAlarm'
        m[f'{key}{name}'] = pct(s['flagged'], s['applicable'])

    def total(ops, pred=lambda s: True):
        sel = [stats[o] for o in ops if pred(stats[o])]
        return (sum(s['applicable'] for s in sel), sum(s['flagged'] for s in sel), sum(s['toolError'] for s in sel))

    a, f, e = total(RESPONSE_OPS)
    ac, fc, _ = total(RESPONSE_OPS, lambda s: s['coupled'])
    au, fu, eu = total(RESPONSE_OPS, lambda s: not s['coupled'])
    m.update({
        'expDetectMutants': str(a),
        'expDetectMutantsFlagged': str(f),
        'expDetectMutantsToolError': str(e),
        'expDetectRecallAll': pct(f, a),
        # Silent mutants: the tool answered without an error, so only the contract could catch it.
        'expDetectMutantsSilent': str(a - e),
        'expDetectRecallSilent': pct(f, a - e),
        'expDetectMutantsCoupled': str(ac),
        'expDetectRecallCoupled': pct(fc, ac),
        'expDetectMutantsUncoupled': str(au),
        'expDetectRecallUncoupled': pct(fu, au),
        'expDetectRecallUncoupledSilent': pct(fu, au - eu),
    })
    ba, bf, _ = total(BENIGN_OPS)
    m.update({
        'expDetectBenignApplicable': str(ba),
        'expDetectBenignFlagged': str(bf),
        'expDetectBenignRate': pct(bf, ba),
        'expDetectBenignWilsonUpper': pct_of(wilson(bf, ba)[1]) if ba else NA,
    })
    controls = [r for r in rows if r['op'] == 'control']
    seeds = {r['seed'].rsplit('#', 1)[-1] for r in rows if r.get('seed')}
    m.update({
        'expDetectControls': str(len(controls)),
        'expDetectControlsMatch': str(sum(1 for r in controls if r.get('matchesLogged') is True)),
        'expDetectUnmatched': str(sum(r.get('unmatched', 0) for r in rows)),
        'expDetectSeeds': str(len(seeds)),
    })
    return m, stats


def build(base, run):
    """(macros, table rows or None, run id or None)."""
    run_id = pick_run(base, run)
    clean = read_jsonl(os.path.join(base, run_id, 'clean.jsonl')) if run_id else []
    mpath = os.path.join(base, run_id, 'mutate.jsonl') if run_id else None
    mrows = read_jsonl(mpath) if mpath and os.path.isfile(mpath) else None
    macros = clean_numbers(clean) if run_id else {k: NA for k in clean_numbers([{'verdict': 'x'}])}
    macros['expDetectRunId'] = run_id or NA
    if mrows is not None:
        mm, stats = mutate_numbers(mrows)
    else:
        mm, _ = mutate_numbers([])
        mm = {k: NA for k in mm}
        stats = None
    macros.update(mm)
    return macros, stats, run_id


def render_macros(macros, run_id):
    lines = [HEADER, f'% run: {run_id or "none"}\n']
    for name in sorted(macros):
        if not name.isalpha():
            raise ValueError(f'macro name must be letters only: {name}')
        lines.append(f'\\newcommand{{\\{name}}}{{{macros[name]}}}\n')
    return ''.join(lines)


def render_table(stats, run_id):
    out = [HEADER, f'% run: {run_id or "none"}\n', '\\begin{tabular}{lrrrrl}\n', '\\toprule\n',
           'Operator & Applicable calls & Flagged & Tool error & Recall & Coupled? \\\\\n', '\\midrule\n']
    if stats is None:
        out.append('\\multicolumn{6}{l}{No E-B mutation run yet.} \\\\\n')
    else:
        for op in RESPONSE_OPS:
            s = stats[op]
            out.append(f"{op} & {s['applicable']} & {s['flagged']} & {s['toolError']} & "
                       f"{pct(s['flagged'], s['applicable'])} & {coupled_cell(s)} \\\\\n")
        out.append('\\midrule\n')
        out.append('\\multicolumn{6}{l}{\\emph{Benign (flagged = false alarm)}} \\\\\n')
        for op in BENIGN_OPS:
            s = stats[op]
            out.append(f"{op} & {s['applicable']} & {s['flagged']} & {s['toolError']} & "
                       f"{pct(s['flagged'], s['applicable'])} & -- \\\\\n")
    out += ['\\bottomrule\n', '\\end{tabular}\n']
    return ''.join(out)


def main(argv):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--dir', default=DEFAULT_DIR)
    p.add_argument('--run')
    p.add_argument('--out', default=DEFAULT_OUT)
    p.add_argument('--check', action='store_true')
    a = p.parse_args(argv)
    if a.run and pick_run(a.dir, a.run) is None:
        print(f'no clean.jsonl for run {a.run} under {a.dir}', file=sys.stderr)
        return 2
    macros, stats, run_id = build(a.dir, a.run)
    outputs = {
        'exp-detect.tex': render_macros(macros, run_id),
        'tab-detect.tex': render_table(stats, run_id),
    }
    if run_id is None:
        print(f'no E-B run under {a.dir}: every number is {NA}')
    if a.check:
        bad = []
        for name, text in outputs.items():
            f = os.path.join(a.out, name)
            if not os.path.isfile(f) or open(f, encoding='utf-8').read() != text:
                bad.append(name)
        for name in bad:
            print(f'FAIL {name} differs from its rebuild (stale or hand-edited)')
        print('exp-detect check ' + ('PASS' if not bad else 'FAIL'))
        return 1 if bad else 0
    os.makedirs(a.out, exist_ok=True)
    for name, text in outputs.items():
        with open(os.path.join(a.out, name), 'w', encoding='utf-8') as f:
            f.write(text)
        print(f'wrote {os.path.join(a.out, name)}')
    print(f"run {run_id or 'none'}: clean calls {macros['expDetectCleanCalls']}, "
          f"violated {macros['expDetectCleanViolated']}, entities {macros['expDetectCleanEntities']}, "
          f"Wilson upper per call {macros['expDetectWilsonUpperCall']}, per entity {macros['expDetectWilsonUpperEntity']}; "
          f"mutants {macros['expDetectMutants']}, flagged {macros['expDetectMutantsFlagged']} "
          f"(recall {macros['expDetectRecallAll']}, silent-only {macros['expDetectRecallSilent']}, "
          f"coupled {macros['expDetectRecallCoupled']}, uncoupled {macros['expDetectRecallUncoupled']}); "
          f"benign flagged {macros['expDetectBenignFlagged']}/{macros['expDetectBenignApplicable']}")
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
