import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ALL_DRIFTS } from '@fiks/vendor-api';
import { formatFiles } from './format.ts';
import type { Trace } from './trace-store.ts';

export interface ReproSpec {
  traceId: string;
  /** The target properties: the test must fail naming each of them. */
  propertyIds: string[];
  /** Relative to the shop-mcp repo. */
  testPath: string;
  tracePath: string;
}

/**
 * Traces stored in shop-mcp must come from the real upstream behavior. An isolated drift
 * profile (some v2 drifts only) still sends the v2 version header, a combination the real
 * vendor never produces, so a correct header-based fix could wrongly fail it.
 */
export function assertStorableProfile(trace: Trace) {
  const u = trace.upstream;
  if (u?.version === 'v2' && (u.drifts?.length ?? 0) !== ALL_DRIFTS.length) {
    throw new Error(
      `trace ${trace.id} was captured under a partial v2 profile [${u.drifts?.join(',')}]; capture under full v2`,
    );
  }
}

export function targetOf(trace: Trace): string[] {
  return trace.target ?? trace.violated.map((v) => v.propertyId);
}

const esc = (s: string) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

export function reproSource(trace: Trace): string {
  const target = targetOf(trace);
  const why = trace.violated
    .filter((v) => target.includes(v.propertyId))
    .map((v) => `//   ${v.propertyId}: ${v.message}`)
    .join('\n');
  return `// Reproduction test generated by fiks from trace ${trace.id}.
// Captured ${trace.capturedAt}: ${trace.tool}(${JSON.stringify(trace.args)}) violated
${why}
// The trace (exact call, upstream HTTP, violation) is ${trace.id}.json next to this file.
import { test } from 'vitest';
import { expectRecordingHolds, loadRecording, outOfScope, targetOf } from '../fiks/check.ts';

const trace = new URL('./${trace.id}.json', import.meta.url).pathname;

test('${esc(target.join(' + '))} holds for ${esc(trace.tool)} [fiks ${trace.id}]', async () => {
  const rec = loadRecording(trace);
  await expectRecordingHolds(trace, { ignore: outOfScope(rec), mustCheck: targetOf(rec) });
});
`;
}

/** Writes the trace and its repro test into a shop-mcp checkout. */
export function generateRepro(trace: Trace, traceFile: string, repoDir: string): ReproSpec {
  assertStorableProfile(trace);
  const target = targetOf(trace);
  const violated = new Set(trace.violated.map((v) => v.propertyId));
  if (target.length === 0) throw new Error(`trace ${trace.id} has no target property`);
  const unknown = target.filter((p) => !violated.has(p));
  if (unknown.length) throw new Error(`trace ${trace.id}: target ${unknown.join(', ')} was not violated`);
  const dir = join(repoDir, 'test/repro');
  mkdirSync(dir, { recursive: true });
  const tracePath = `test/repro/${trace.id}.json`;
  const testPath = `test/repro/${trace.id}.test.ts`;
  copyFileSync(traceFile, join(repoDir, tracePath));
  writeFileSync(join(repoDir, testPath), reproSource(trace));
  formatFiles(repoDir, [tracePath, testPath]);
  return { traceId: trace.id, propertyIds: targetOf(trace), testPath, tracePath };
}
