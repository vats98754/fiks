// `fiks seed-tag --domain tracker` (ORCH; PLAN 8.1 A0, P15): re-vendors the contract evaluator
// (with `disabled` support, VOCAB) and the frozen contracts into the domain's tool repo and tags
// the result (default `seed-tracker-v1`, the base of the tracker drifts).
//
//   pnpm fiks seed-tag --domain tracker [--repo <clone>] [--from <ref>] [--tag <name>]
//                      [--contracts <file>] [--dry-run] [--json]
//
// Vendored, each with the same generated header as scripts/sync-contracts.mjs:
//   packages/contracts/src/types.ts    -> test/fiks/vendored/types.ts
//   packages/contracts/src/evaluate.ts -> test/fiks/vendored/evaluate.ts
//   the frozen contracts               -> test/fiks/vendored/<server>.contracts.json
// The frozen contracts are --contracts, else the Domain's contractsPath (written at A0), else the
// repo's own working-tree copy of the vendored contracts (e.g. after scripts/contract-disable.mjs
// disabled a property at A0). The commit is made in a throwaway worktree of the clone at --from
// (default HEAD), so the clone's checkout is untouched; then an annotated tag. Nothing is pushed:
// publishing the tag is a separate, approved run step.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { getDomain } from '@fiks/domains';
import type { CliCommandModule } from '@fiks/interfaces';
import { ROOT, repoDir } from '../paths.ts';

/** Byte-identical to scripts/sync-contracts.mjs's HEADER. */
export const VENDOR_HEADER =
  '// GENERATED by fiks scripts/sync-contracts.mjs from packages/contracts. Do not edit.\n';

const DEFAULT_TAG: Record<string, string> = { tracker: 'seed-tracker-v1' };

export interface SeedTagPlan {
  domain: string;
  repo: string;
  from: string;
  fromCommit: string;
  tag: string;
  contractsSource: string;
  /** What a real run needs and does not have (a dry run lists it; a real run refuses). */
  missing: string[];
  files: { path: string; source: string; changed: boolean; bytes: string }[];
}

const git = (cwd: string, ...args: string[]) =>
  execFileSync('git', ['-c', 'core.hooksPath=/dev/null', ...args], {
    cwd,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  }).trim();

function blobAt(repo: string, commit: string, path: string): string | null {
  try {
    return execFileSync('git', ['show', `${commit}:${path}`], {
      cwd: repo,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    });
  } catch {
    return null;
  }
}

export class SeedTagError extends Error {}

export function planSeedTag(o: {
  domain: string;
  repo?: string;
  from?: string;
  tag?: string;
  contracts?: string;
}): SeedTagPlan {
  const d = getDomain(o.domain);
  const repo = resolve(o.repo ?? repoDir(o.domain));
  if (!existsSync(join(repo, '.git'))) throw new SeedTagError(`${repo} is not a git checkout`);
  const from = o.from ?? 'HEAD';
  let fromCommit: string;
  try {
    fromCommit = git(repo, 'rev-parse', '--verify', '--quiet', '--end-of-options', `${from}^{commit}`);
  } catch {
    throw new SeedTagError(`unknown --from ${from} in ${repo}`);
  }
  const tag = o.tag ?? DEFAULT_TAG[o.domain] ?? `seed-${o.domain}-v1`;
  if (!/^[A-Za-z0-9][\w.-]{0,100}$/.test(tag)) throw new SeedTagError(`bad tag name ${tag}`);
  const server = d.repo.slug.split('/').pop() ?? o.domain;
  const vendoredContracts = `test/fiks/vendored/${server}.contracts.json`;
  const contractsSource = o.contracts
    ? resolve(o.contracts)
    : existsSync(d.contractsPath)
      ? d.contractsPath
      : join(repo, vendoredContracts);
  const contractsReady = existsSync(contractsSource);
  if (contractsReady) JSON.parse(readFileSync(contractsSource, 'utf8')); // must be JSON
  const sources: { path: string; source: string; bytes: string }[] = [
    {
      path: 'test/fiks/vendored/types.ts',
      source: join(ROOT, 'packages/contracts/src/types.ts'),
      bytes: VENDOR_HEADER + readFileSync(join(ROOT, 'packages/contracts/src/types.ts'), 'utf8'),
    },
    {
      path: 'test/fiks/vendored/evaluate.ts',
      source: join(ROOT, 'packages/contracts/src/evaluate.ts'),
      bytes: VENDOR_HEADER + readFileSync(join(ROOT, 'packages/contracts/src/evaluate.ts'), 'utf8'),
    },
  ];
  if (contractsReady)
    sources.push({
      path: vendoredContracts,
      source: contractsSource,
      bytes: readFileSync(contractsSource, 'utf8'),
    });
  return {
    domain: o.domain,
    repo,
    from,
    fromCommit,
    tag,
    contractsSource,
    missing: contractsReady
      ? []
      : [
          `${vendoredContracts}: no frozen contracts yet (pass --contracts, write ${d.contractsPath} at A0, or vendor them into the repo first)`,
        ],
    files: sources.map((s) => ({ ...s, changed: blobAt(repo, fromCommit, s.path) !== s.bytes })),
  };
}

/** Commits the vendored files on top of --from (in a throwaway worktree) and tags the commit. */
export function applySeedTag(plan: SeedTagPlan): { commit: string; tag: string } {
  if (plan.missing.length) throw new SeedTagError(plan.missing.join('; '));
  try {
    git(plan.repo, 'rev-parse', '--verify', '--quiet', `refs/tags/${plan.tag}`);
    throw new SeedTagError(`tag ${plan.tag} already exists in ${plan.repo}; tags are never moved`);
  } catch (e) {
    if (e instanceof SeedTagError) throw e;
  }
  const dir = join(mkdtempSync(join(tmpdir(), 'fiks-seed-tag-')), 'wt');
  git(plan.repo, 'worktree', 'add', '--detach', dir, plan.fromCommit);
  try {
    for (const f of plan.files) {
      mkdirSync(dirname(join(dir, f.path)), { recursive: true });
      writeFileSync(join(dir, f.path), f.bytes);
    }
    git(dir, 'add', '--', ...plan.files.map((f) => f.path));
    const id = ['-c', 'user.name=fiks', '-c', 'user.email=fiks@localhost'];
    const changed = plan.files.filter((f) => f.changed).map((f) => f.path);
    if (changed.length)
      git(
        dir,
        ...id,
        'commit',
        '-q',
        '-m',
        `test(fiks): re-vendor the contract evaluator and frozen contracts (seed-tag ${plan.tag})`,
        '-m',
        changed.join('\n'),
      );
    const commit = git(dir, 'rev-parse', 'HEAD');
    git(
      dir,
      ...id,
      'tag',
      '-a',
      plan.tag,
      '-m',
      `fiks seed-tag ${plan.domain}: ${changed.length} file(s) re-vendored`,
      commit,
    );
    return { commit, tag: plan.tag };
  } finally {
    try {
      git(plan.repo, 'worktree', 'remove', '--force', dir);
    } catch {
      rmSync(dir, { recursive: true, force: true });
    }
  }
}

const command: CliCommandModule = {
  name: 'seed-tag',
  describe: 're-vendor the evaluator and frozen contracts into a domain repo and tag it (no push)',
  run(argv) {
    let values: Record<string, string | boolean | undefined>;
    try {
      ({ values } = parseArgs({
        args: argv,
        options: {
          domain: { type: 'string' },
          repo: { type: 'string' },
          from: { type: 'string' },
          tag: { type: 'string' },
          contracts: { type: 'string' },
          'dry-run': { type: 'boolean', default: false },
          json: { type: 'boolean', default: false },
          help: { type: 'boolean', default: false },
        },
      }));
    } catch (e) {
      console.error(`seed-tag: ${e instanceof Error ? e.message : String(e)}`);
      return 2;
    }
    if (values.help || !values.domain) {
      console.error(
        'usage: fiks seed-tag --domain tracker [--repo <clone>] [--from <ref>] [--tag <name>] [--contracts <file>] [--dry-run] [--json]',
      );
      return values.help ? 0 : 2;
    }
    let plan: SeedTagPlan;
    try {
      plan = planSeedTag({
        domain: values.domain as string,
        repo: values.repo as string | undefined,
        from: values.from as string | undefined,
        tag: values.tag as string | undefined,
        contracts: values.contracts as string | undefined,
      });
    } catch (e) {
      console.error(`seed-tag: ${e instanceof Error ? e.message : String(e)}`);
      return 2;
    }
    const listing = {
      domain: plan.domain,
      repo: plan.repo,
      from: `${plan.from} = ${plan.fromCommit}`,
      tag: plan.tag,
      contracts: plan.contractsSource,
      files: plan.files.map((f) => ({ path: f.path, source: f.source, changed: f.changed })),
      missing: plan.missing,
    };
    if (values['dry-run']) {
      if (values.json) console.log(JSON.stringify({ dryRun: true, ...listing }, null, 2));
      else
        console.log(
          [
            `seed-tag --dry-run (${plan.domain}): would tag ${plan.tag} in ${plan.repo} on top of ${plan.fromCommit.slice(0, 12)}`,
            ...plan.files.map((f) => `  ${f.changed ? 'vendor' : 'same  '} ${f.path} <- ${f.source}`),
            ...plan.missing.map((m) => `  MISSING ${m}`),
          ].join('\n'),
        );
      return 0;
    }
    try {
      const r = applySeedTag(plan);
      if (values.json) console.log(JSON.stringify({ ...listing, ...r }, null, 2));
      else console.log(`tagged ${r.tag} = ${r.commit} in ${plan.repo} (not pushed)`);
      return 0;
    } catch (e) {
      console.error(`seed-tag: ${e instanceof Error ? e.message : String(e)}`);
      return e instanceof SeedTagError ? 2 : 1;
    }
  },
};

export default command;
