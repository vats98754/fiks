// The tracker Domain's repro and repair hooks (PLAN P8, round 5): the repro files in tracker-mcp's
// test/fiks layout (same shape as shop-mcp's), tracker-mcp's whole vitest suite, and the repair
// edit allow-list. Self-contained: wave-1 streams import only the CORE seed.
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, realpathSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, relative } from 'node:path';
import type {
  AllowedEditPaths,
  DomainSuite,
  FailedTest,
  FileResult,
  ReproEmitter,
  ReproTrace,
  SuiteRun,
} from '@fiks/interfaces';

/** Repair edit allow-list: tracker-mcp's source files only. */
export const TRACKER_ALLOWED_EDIT_PATHS: AllowedEditPaths = ['^src/.+\\.ts$'];

/** `**` = the whole suite. */
export const WHOLE_SUITE: readonly string[] = ['**'];

export function targetOf(trace: Pick<ReproTrace, 'target' | 'violated'>): string[] {
  return trace.target ?? trace.violated.map((v) => v.propertyId);
}

const esc = (s: string) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

/** The repro test for a trace, importing tracker-mcp's `test/fiks/check.ts` (shop-mcp's layout). */
export function trackerReproSource(trace: ReproTrace, traceFileName: string): string {
  const target = targetOf(trace);
  const why = trace.violated
    .filter((v) => target.includes(v.propertyId))
    .map((v) => `//   ${v.propertyId}: ${v.message.replace(/\n/g, ' ')}`)
    .join('\n');
  return `// Reproduction test generated by fiks from trace ${trace.id}.
// Captured ${trace.capturedAt}: ${trace.tool}(${JSON.stringify(trace.args)}) violated
${why}
// The trace (exact call, upstream HTTP, violation) is ${traceFileName} next to this file.
import { test } from 'vitest';
import { expectRecordingHolds, loadRecording, outOfScope, targetOf } from '../fiks/check.ts';

const trace = new URL('./${esc(traceFileName)}', import.meta.url).pathname;

test('${esc(target.join(' + '))} holds for ${esc(trace.tool)} [fiks ${esc(trace.id)}]', async () => {
  const rec = loadRecording(trace);
  await expectRecordingHolds(trace, { ignore: outOfScope(rec), mustCheck: targetOf(rec) });
});
`;
}

/**
 * Writes nothing: returns `spec.tracePath` (the trace JSON, 2-space indented; tracker-mcp's Biome
 * config does not format test/repro/*.json) and `spec.testPath` (the repro test, already in
 * Biome's format). Both paths must lie next to each other under `test/repro/`.
 */
export const trackerReproEmitter: ReproEmitter = (trace, spec) => {
  const target = targetOf(trace);
  if (target.length === 0) throw new Error(`trace ${trace.id} has no target property`);
  const violated = new Set(trace.violated.map((v) => v.propertyId));
  const unknown = target.filter((p) => !violated.has(p));
  if (unknown.length) throw new Error(`trace ${trace.id}: target ${unknown.join(', ')} was not violated`);
  const dir = (p: string) => p.slice(0, p.lastIndexOf('/') + 1);
  if (!spec.testPath.startsWith('test/') || dir(spec.testPath) !== dir(spec.tracePath)) {
    throw new Error(
      `repro test and trace must sit together under test/ (${spec.testPath}, ${spec.tracePath})`,
    );
  }
  const traceFileName = spec.tracePath.slice(dir(spec.tracePath).length);
  return {
    files: [
      { path: spec.tracePath, bytes: `${JSON.stringify(trace, null, 2)}\n` },
      { path: spec.testPath, bytes: trackerReproSource(trace, traceFileName) },
    ],
    testPath: spec.testPath,
  };
};

// --- Suite ----------------------------------------------------------------------------------

interface VitestJson {
  testResults: {
    name: string;
    status: string;
    message?: string;
    assertionResults: { fullName: string; status: string; failureMessages: string[] }[];
  }[];
}

/** A repo-relative glob (`**`, `*`, `?`) as an anchored regular expression. */
export function globToRegExp(glob: string): RegExp {
  let re = '';
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i] as string;
    if (c === '*' && glob[i + 1] === '*') {
      if (glob[i + 2] === '/') {
        re += '(?:.*/)?';
        i += 2;
      } else {
        re += '.*';
        i += 1;
      }
    } else if (c === '*') re += '[^/]*';
    else if (c === '?') re += '[^/]';
    else re += c.replace(/[.+^${}()|[\]\\]/g, '\\$&');
  }
  return new RegExp(`^${re}$`);
}

export const inScope = (file: string, scope: readonly string[] = WHOLE_SUITE) =>
  scope.some((g) => globToRegExp(g).test(file));

const isWholeSuite = (scope: readonly string[]) => scope.length === 1 && scope[0] === '**';

/**
 * Runs tracker-mcp's vitest suite in `repoDir` (`node_modules/.bin/vitest run --reporter=json`)
 * and reports what ran and what failed, as `@fiks/repro` runSuite does for shop-mcp. A narrower
 * scope passes its literal path prefixes to vitest as filters; callers judge failures in scope.
 */
export function runTrackerSuite(repoDir: string, scope: readonly string[] = WHOLE_SUITE): SuiteRun {
  const out = join(mkdtempSync(join(tmpdir(), 'fiks-tracker-suite-')), 'vitest.json');
  const filters = isWholeSuite(scope) ? [] : scope.map((g) => g.split(/[*?]/)[0] ?? '').filter(Boolean);
  // A generous per-test timeout: a busy machine must not turn into a gate verdict.
  const args = ['run', '--reporter=json', `--outputFile=${out}`, '--testTimeout=60000', ...filters];
  const command = `vitest ${args.join(' ')}`;
  const r = spawnSync(join(repoDir, 'node_modules/.bin/vitest'), args, { cwd: repoDir, encoding: 'utf8' });
  let report: VitestJson;
  try {
    report = JSON.parse(readFileSync(out, 'utf8')) as VitestJson;
  } catch {
    const tail = (r.stderr || r.stdout || '').slice(0, 2000);
    return {
      exitCode: r.status ?? 1,
      failed: [],
      files: [],
      suiteErrors: [`no vitest report: ${tail}`],
      logPath: out,
      command,
    };
  }
  const realRepo = realpathSync(repoDir);
  const failed: FailedTest[] = [];
  const files: FileResult[] = [];
  const suiteErrors: string[] = [];
  for (const file of report.testResults) {
    const rel = relative(realRepo, realpathSync(file.name));
    files.push({ file: rel, statuses: file.assertionResults.map((a) => a.status) });
    const fails = file.assertionResults.filter((a) => a.status === 'failed');
    for (const a of fails)
      failed.push({ file: rel, test: a.fullName, message: a.failureMessages.join('\n').slice(0, 4000) });
    if (file.status === 'failed' && fails.length === 0)
      suiteErrors.push(`${rel}: ${file.message ?? 'suite failed to run'}`);
  }
  return { exitCode: r.status ?? 1, failed, files, suiteErrors, logPath: out, command };
}

/** tracker-mcp's whole vitest suite (scope `**`). */
export const trackerSuite: DomainSuite = {
  scope: WHOLE_SUITE,
  run: (repoDir, scope = WHOLE_SUITE) => runTrackerSuite(repoDir, scope),
  oneFailingInScope: (run, scope = WHOLE_SUITE) =>
    run.failed.filter((f) => inScope(f.file, scope)).length === 1,
};
