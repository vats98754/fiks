#!/usr/bin/env node
// Vendors the contract evaluator and shop-mcp contracts into the shop-mcp test suite, so
// shop-mcp CI runs the exact contracts the fiks proxy enforces, and keeps shop-mcp's copy of
// the vendor's published spec current. `--check` only compares (against the clone's working
// tree); `--check --ref <sha>` compares against the git objects at that commit of the clone
// (`git show <sha>:<path>`), so the result does not depend on what the clone has checked out.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { parseArgs } from 'node:util';

const root = new URL('..', import.meta.url).pathname;
const shop = process.env.FIKS_SHOP_DIR ?? join(root, '.work/shop-mcp');
const HEADER = '// GENERATED by fiks scripts/sync-contracts.mjs from packages/contracts. Do not edit.\n';

/** `to` is relative to the shop-mcp repo root. */
const files = [
  { from: 'packages/contracts/src/types.ts', to: 'test/fiks/vendored/types.ts', header: HEADER },
  { from: 'packages/contracts/src/evaluate.ts', to: 'test/fiks/vendored/evaluate.ts', header: HEADER },
  {
    from: 'packages/contracts/contracts/shop-mcp.contracts.json',
    to: 'test/fiks/vendored/shop-mcp.contracts.json',
    header: '',
  },
  { from: 'packages/vendor-api/openapi.json', to: 'vendor/openapi.json', header: '' },
];

const { values } = parseArgs({
  options: { check: { type: 'boolean', default: false }, ref: { type: 'string' } },
});
const check = values.check;
const ref = values.ref;
if (ref !== undefined && !check) {
  console.error('[sync-contracts] --ref only compares; use it with --check');
  process.exit(2);
}

if (ref !== undefined) {
  try {
    execFileSync('git', ['cat-file', '-e', `${ref}^{commit}`], { cwd: shop, stdio: 'ignore' });
  } catch {
    console.error(
      `[sync-contracts] ${ref} is not a commit in ${shop}; run node scripts/ensure-shop-mcp.mjs first`,
    );
    process.exit(1);
  }
}

/** The file at `rel` in the clone: at commit `ref` when given, else in the working tree. */
function have(rel) {
  if (ref === undefined) {
    const target = join(shop, rel);
    return existsSync(target) ? readFileSync(target, 'utf8') : null;
  }
  try {
    return execFileSync('git', ['show', `${ref}:${rel}`], {
      cwd: shop,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      maxBuffer: 64 * 1024 * 1024,
    });
  } catch {
    return null;
  }
}

const stale = [];
for (const f of files) {
  const want = f.header + readFileSync(join(root, f.from), 'utf8');
  if (have(f.to) === want) continue;
  if (check) {
    stale.push(`shop-mcp/${f.to}`);
    continue;
  }
  const target = join(shop, f.to);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, want);
  console.log(`[sync-contracts] wrote ${target.replace(root, '')}`);
}
const where = ref === undefined ? shop : `${shop} at ${ref}`;
if (check && stale.length) {
  console.error(
    `[sync-contracts] out of date in ${where}: ${stale.join(', ')}. Run node scripts/sync-contracts.mjs`,
  );
  process.exit(1);
}
if (check) console.log(`[sync-contracts] vendored contracts are identical (${where})`);
