#!/usr/bin/env node
// Vendors the contract evaluator and shop-mcp contracts into the shop-mcp test suite, so
// shop-mcp CI runs the exact contracts the fiks proxy enforces, and keeps shop-mcp's copy of
// the vendor's published spec current. `--check` only compares.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const shop = process.env.FIKS_SHOP_DIR ?? join(root, '.work/shop-mcp');
const vendored = join(shop, 'test/fiks/vendored');
const HEADER = '// GENERATED by fiks scripts/sync-contracts.mjs from packages/contracts. Do not edit.\n';

const files = [
  { from: 'packages/contracts/src/types.ts', to: join(vendored, 'types.ts'), header: HEADER },
  { from: 'packages/contracts/src/evaluate.ts', to: join(vendored, 'evaluate.ts'), header: HEADER },
  {
    from: 'packages/contracts/contracts/shop-mcp.contracts.json',
    to: join(vendored, 'shop-mcp.contracts.json'),
    header: '',
  },
  { from: 'packages/vendor-api/openapi.json', to: join(shop, 'vendor/openapi.json'), header: '' },
];

const check = process.argv.includes('--check');
const stale = [];
for (const f of files) {
  const want = f.header + readFileSync(join(root, f.from), 'utf8');
  const target = f.to;
  const have = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (have === want) continue;
  if (check) {
    stale.push(target.replace(shop, 'shop-mcp'));
    continue;
  }
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, want);
  console.log(`[sync-contracts] wrote ${target.replace(root, '')}`);
}
if (check && stale.length) {
  console.error(
    `[sync-contracts] out of date in ${shop}: ${stale.join(', ')}. Run node scripts/sync-contracts.mjs`,
  );
  process.exit(1);
}
if (check) console.log('[sync-contracts] vendored contracts are identical');
